//! Generated CLI reference, man pages, doctor catalog, and demo screenshot.
//!
//! `NUT_UPDATE_GOLDENS=1` (via `just docs-gen`) writes the committed files.
//! Otherwise the test fails with "run `just docs-gen`".

use clap::{Command, CommandFactory};
use clap_mangen::Man;
use nut_cli::cli::{COMMAND_GROUPS, Cli};
use nut_cli::fake_upsd::{FakeUpsdFixture, serve_client};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::net::TcpListener;
use std::path::{Path, PathBuf};
use std::process::Command as Process;
use std::thread;

const GOLDENS_ENV: &str = "NUT_UPDATE_GOLDENS";
const GENERATOR: &str = "tests/docs_gen.rs";
const CLI_DIR: &str = "docs/reference/cli";
const MAN_DIR: &str = "man";
const SCREENSHOT_TXT: &str = "docs/screenshot.txt";
const SCREENSHOT_SVG: &str = "docs/screenshot.svg";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn update_goldens() -> bool {
    std::env::var_os(GOLDENS_ENV).is_some()
}

fn capture_help(args: &[&str]) -> String {
    let output = Process::new(env!("CARGO_BIN_EXE_nut"))
        .args(args)
        .arg("--help")
        .env("COLUMNS", "80")
        .env("NO_COLOR", "1")
        .env("TERM", "dumb")
        .env_remove("CLICOLOR_FORCE")
        .output()
        .unwrap_or_else(|error| panic!("run nut {} --help: {error}", args.join(" ")));
    assert!(
        output.status.success(),
        "nut {} --help failed: {}",
        args.join(" "),
        String::from_utf8_lossy(&output.stderr)
    );
    let help = String::from_utf8(output.stdout).expect("help is UTF-8");
    assert!(
        !help.as_bytes().contains(&0x1b),
        "nut {} --help must not emit ANSI",
        args.join(" ")
    );
    normalize_text(&help)
}

fn normalize_text(text: &str) -> String {
    let mut body = text
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    if !body.ends_with('\n') {
        body.push('\n');
    }
    body
}

fn help_fence(body: &str) -> String {
    format!("```text\n{}\n```\n", body.trim_end_matches('\n'))
}

fn about(command: &Command) -> String {
    command
        .get_about()
        .map(ToString::to_string)
        .unwrap_or_default()
}

fn visible_children(command: &Command) -> Vec<&Command> {
    command
        .get_subcommands()
        .filter(|child| !child.is_hide_set())
        .collect()
}

fn render_command_page(name: &str, command: &Command, path: &[&str]) -> String {
    let mut page = format!(
        "<!-- generated by {GENERATOR}; run `just docs-gen` -->\n\n# nut {name}\n\n{}\n\n{}",
        about(command),
        help_fence(&capture_help(path))
    );
    for child in visible_children(command) {
        let child_name = child.get_name();
        let mut child_path = path.to_vec();
        child_path.push(child_name);
        page.push_str(&format!(
            "\n## nut {name} {child_name}\n\n{}\n\n{}",
            about(child),
            help_fence(&capture_help(&child_path))
        ));
        for grandchild in visible_children(child) {
            let grandchild_name = grandchild.get_name();
            let mut grandchild_path = child_path.clone();
            grandchild_path.push(grandchild_name);
            page.push_str(&format!(
                "\n### nut {name} {child_name} {grandchild_name}\n\n{}\n\n{}",
                about(grandchild),
                help_fence(&capture_help(&grandchild_path))
            ));
        }
    }
    page.push_str("\n## Related\n\n- [CLI reference](index.md)\n- [Getting started](../../getting-started.md)\n");
    page
}

fn render_index(root_help: &str, command: &Command) -> String {
    let mut page = format!(
        "<!-- generated by {GENERATOR}; run `just docs-gen` -->\n\n# CLI reference\n\nEvery `nut` command, generated from the same help text `nut --help` prints. Man pages live in [`man/`](../../../man/).\n\n"
    );
    let subcommands: BTreeMap<String, String> = visible_children(command)
        .into_iter()
        .map(|child| (child.get_name().to_owned(), about(child)))
        .collect();
    for &(heading, names) in COMMAND_GROUPS {
        page.push_str(&format!(
            "## {heading}\n\n| Command | What it does |\n| --- | --- |\n"
        ));
        for name in names {
            let about = subcommands
                .get(*name)
                .unwrap_or_else(|| panic!("{name} missing from clap tree"));
            page.push_str(&format!("| [`nut {name}`]({name}.md) | {about} |\n"));
        }
        page.push('\n');
    }
    page.push_str(&format!("## Full help\n\n{}", help_fence(root_help)));
    page.push_str("\n## Related\n\n- [Getting started](../../getting-started.md)\n- [Design language](../../design.md)\n- [Safety contract](../../safety.md)\n");
    page
}

fn expected_cli_pages(command: &Command) -> BTreeMap<String, String> {
    let mut pages = BTreeMap::new();
    let root_help = capture_help(&[]);
    pages.insert("index.md".into(), render_index(&root_help, command));
    for child in visible_children(command) {
        let name = child.get_name();
        pages.insert(
            format!("{name}.md"),
            render_command_page(name, child, &[name]),
        );
    }
    pages
}

fn render_man(command: Command, display: &str, bin_name: &str) -> Vec<u8> {
    let command = command.display_name(display).bin_name(bin_name);
    let man = Man::new(command)
        .source(format!("nut-cli {}", env!("CARGO_PKG_VERSION")))
        .manual("nut");
    let mut buffer = Vec::new();
    man.render(&mut buffer).expect("render man page");
    buffer
}

fn expected_man_pages(root: &Command) -> BTreeMap<String, Vec<u8>> {
    let mut pages = BTreeMap::new();
    pages.insert("nut.1".into(), render_man(root.clone(), "nut", "nut"));
    for child in visible_children(root) {
        let name = child.get_name();
        let display = format!("nut-{name}");
        let bin = format!("nut {name}");
        pages.insert(
            format!("{display}.1"),
            render_man(child.clone(), &display, &bin),
        );
    }
    pages
}

fn sync_text_dir(dir: &Path, expected: &BTreeMap<String, String>, update: bool) {
    fs::create_dir_all(dir).unwrap();
    let mut on_disk = BTreeSet::new();
    for entry in fs::read_dir(dir).unwrap() {
        let name = entry.unwrap().file_name();
        let name = name.to_str().expect("utf-8 filename").to_owned();
        if name.starts_with('.') {
            continue;
        }
        on_disk.insert(name);
    }
    if update {
        for name in &on_disk {
            if !expected.contains_key(name) {
                fs::remove_file(dir.join(name)).unwrap();
            }
        }
        for (name, contents) in expected {
            fs::write(dir.join(name), contents).unwrap();
        }
        return;
    }
    let expected_names: BTreeSet<_> = expected.keys().cloned().collect();
    assert_eq!(
        on_disk,
        expected_names,
        "{} drifted; run `just docs-gen`",
        dir.display()
    );
    for (name, contents) in expected {
        let actual = fs::read_to_string(dir.join(name)).unwrap_or_default();
        assert_eq!(
            actual,
            *contents,
            "{} drifted; run `just docs-gen`",
            dir.join(name).display()
        );
    }
}

