fn escape_xml(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            _ => out.push(ch),
        }
    }
    out
}

fn text_to_svg(text: &str) -> String {
    let lines: Vec<&str> = text.lines().collect();
    let cols = lines
        .iter()
        .map(|line| line.chars().count())
        .max()
        .unwrap_or(40)
        .max(40);
    let rows = lines.len().max(1);
    let char_w = 8.4;
    let line_h = 18.0;
    let pad = 16.0;
    let width = cols as f64 * char_w + pad * 2.0;
    let height = rows as f64 * line_h + pad * 2.0;
    let mut svg = format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0}" height="{height:.0}" viewBox="0 0 {width:.1} {height:.1}" role="img" aria-label="nut status demo">
  <rect width="100%" height="100%" rx="8" fill="#0d1117"/>
  <text font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="13" fill="#c9d1d9" xml:space="preserve">
"##
    );
    for (index, line) in lines.iter().enumerate() {
        let y = pad + line_h * (index as f64 + 0.85);
        svg.push_str(&format!(
            "    <tspan x=\"{pad}\" y=\"{y:.1}\">{}</tspan>\n",
            escape_xml(line)
        ));
    }
    svg.push_str("  </text>\n</svg>\n");
    svg
}

fn capture_demo_status(root: &Path) -> String {
    let listener = TcpListener::bind(("127.0.0.1", 0)).unwrap();
    let port = listener.local_addr().unwrap().port();
    let mut fixture = FakeUpsdFixture::read(&root.join("examples/fixtures/demo-ups.json")).unwrap();
    let server = thread::spawn(move || {
        let (stream, _) = listener.accept().unwrap();
        serve_client(stream, &mut fixture).unwrap();
    });
    let output = Process::new(env!("CARGO_BIN_EXE_nut"))
        .args([
            "--color",
            "never",
            "--config",
            "examples/demo.toml",
            "status",
            "--upsd-port",
            &port.to_string(),
        ])
        .current_dir(root)
        .env("COLUMNS", "80")
        .env("NO_COLOR", "1")
        .env("LANG", "C.UTF-8")
        .env("LC_ALL", "C.UTF-8")
        .env("TERM", "xterm")
        .env_remove("CLICOLOR_FORCE")
        .output()
        .expect("run nut status demo");
    server.join().unwrap();
    assert!(
        output.status.success(),
        "demo status failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    normalize_text(&String::from_utf8(output.stdout).expect("demo status is UTF-8"))
}

fn sync_file(path: &Path, expected: &str, update: bool) {
    if update {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).unwrap();
        }
        fs::write(path, expected).unwrap();
        return;
    }
    let actual = fs::read_to_string(path).unwrap_or_default();
    assert_eq!(
        actual,
        expected,
        "{} drifted; run `just docs-gen`",
        path.display()
    );
}

#[test]
fn generated_docs_match() {
    let root = repo_root();
    let update = update_goldens();
    let mut command = Cli::command();
    command.build();

    sync_text_dir(&root.join(CLI_DIR), &expected_cli_pages(&command), update);
    sync_bytes_dir(&root.join(MAN_DIR), &expected_man_pages(&command), update);
    sync_file(
        &root.join("docs/doctor-checks.md"),
        &nut_cli::doctor::catalog_markdown(),
        update,
    );

    let screenshot = capture_demo_status(&root);
    assert!(
        screenshot.contains("nut status · demo"),
        "unexpected demo screen:\n{screenshot}"
    );
    sync_file(&root.join(SCREENSHOT_TXT), &screenshot, update);
    sync_file(
        &root.join(SCREENSHOT_SVG),
        &text_to_svg(&screenshot),
        update,
    );
}

#[test]
fn install_smoke_every_command() {
    let binary = std::env::var_os("NUT_SMOKE_BINARY")
        .unwrap_or_else(|| std::ffi::OsString::from(env!("CARGO_BIN_EXE_nut")));
    let root = repo_root();
    let config = root.join("examples/host.toml");
    let cases: &[&[&str]] = &[
        &["--version"],
        &["--config", config.to_str().unwrap(), "config", "path"],
        &["--config", config.to_str().unwrap(), "config", "show"],
        &["doctor", "--list"],
        &["bios", "profile", "list"],
        &["completion", "zsh"],
        &["completion", "bash"],
        &["drill"],
    ];
    for args in cases {
        let output = Process::new(&binary)
            .args(*args)
            .env("COLUMNS", "80")
            .env("NO_COLOR", "1")
            .env_remove("CLICOLOR_FORCE")
            .output()
            .unwrap_or_else(|error| panic!("run nut {}: {error}", args.join(" ")));
        assert!(
            output.status.success(),
            "nut {} failed ({:?}): {}",
            args.join(" "),
            output.status.code(),
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(
            !output.stdout.is_empty(),
            "nut {} printed no stdout",
            args.join(" ")
        );
    }
}
